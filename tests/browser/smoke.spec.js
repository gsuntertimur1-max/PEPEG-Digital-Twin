import { test, expect } from '@playwright/test';
import * as THREE from 'three';
import { CAMERA_PRESETS, WAREHOUSES, stackLayout } from '../../src/data/layout.js';
test('real WebGL scene, interactions, persistence, reset and local-only requests',async({page})=>{
  const errors=[], external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request',r=>{if(!new URL(r.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/))external.push(r.url());});
  await page.goto('/');
  await expect(page.getByText('PEPEG DIGITAL TWIN',{exact:true})).toBeVisible();
  await expect(page.locator('canvas')).toBeVisible();
  await page.waitForFunction(()=>{
    const c=document.querySelector('canvas');const gl=c?.getContext('webgl2');if(!gl)return false;
    return !gl.isContextLost() && gl.drawingBufferWidth > 0 && gl.getParameter(gl.VERSION).includes('WebGL 2');
  });
  await page.waitForTimeout(1500);
  await page.screenshot({path:'docs/screenshot-overview.png'});
  const label=page.getByRole('button',{name:'GBB 21',exact:false});
  const before=await label.boundingBox();
  await page.mouse.move(600,500);await page.mouse.wheel(0,180);await page.waitForTimeout(600);
  const after=await label.boundingBox();expect(Math.abs(before.x-after.x)+Math.abs(before.y-after.y)).toBeGreaterThan(2);
  await page.getByRole('button',{name:'GBB 18',exact:false}).first().click();
  await expect(page.locator('.details-card h2')).toHaveText('GBB 18');
  await page.getByRole('button',{name:'OPEN ROOF',exact:true}).click();
  await page.waitForTimeout(2600);
  // Project the actual 18/A02 mesh into screen coordinates, then click via R3F raycasting.
  const r = await page.locator('canvas').boundingBox();
  const preset=CAMERA_PRESETS['GBB 18'];
  const camera=new THREE.PerspectiveCamera(42,r.width/r.height,.1,1000);
  camera.position.fromArray(preset.pos);camera.lookAt(new THREE.Vector3(...preset.target));camera.updateMatrixWorld();
  const w=WAREHOUSES.find(w=>w.name==='GBB 18'), slot=stackLayout(w.name,'A',2);
  const p=new THREE.Vector3(w.x+slot.position[0],slot.position[1]+slot.size[1]/2,w.z+slot.position[2]).project(camera);
  const point={x:r.x+(p.x+1)*r.width/2,y:r.y+(1-p.y)*r.height/2};
  await page.mouse.click(point.x,point.y);
  await expect(page.locator('.details-card h2')).toHaveText('18/A02');
  await expect(page.locator('.fefo-box')).toContainText('PRIORITAS KELUAR');
  await page.getByLabel('Jumlah reservasi').fill('400');
  await page.getByRole('button',{name:'SIMPAN RESERVASI'}).click();
  await expect(page.locator('.detail-grid').first()).toContainText('400');
  await page.waitForTimeout(1400);
  await page.screenshot({path:'docs/screenshot-interior.png'});
  await page.getByRole('button',{name:'B 9123 UQ',exact:false}).last().click();
  await page.getByRole('button',{name:'LANJUTKAN STATUS'}).click();
  await expect(page.locator('.details-card')).toContainText('SEDANG BONGKAR');
  await page.getByRole('button',{name:'LANJUTKAN STATUS'}).click();
  await expect(page.getByRole('button',{name:'PROSES SELESAI'})).toBeDisabled();
  const claim=page.getByTestId('CLM-002');
  await claim.getByLabel('Pemenuhan CLM-002').fill('10');await claim.getByRole('button',{name:'PENUHI KLAIM'}).click();
  await expect(claim.getByTestId('claim-remaining')).toHaveText('15 kg');
  await expect(page.locator('.kpi-card').last()).toContainText('21 kg');
  const smallClaim=page.getByTestId('CLM-001');await smallClaim.getByRole('button',{name:'PENUHI KLAIM'}).click();
  await expect(smallClaim).toContainText('SETTLED');await expect(smallClaim.getByTestId('claim-remaining')).toHaveText('0 kg');
  await page.getByLabel('Camera preset').selectOption('GBB 17');await page.getByRole('button',{name:'A01',exact:true}).click();
  await page.getByRole('button',{name:'TANDAI PRIORITAS FEFO'}).click();
  await expect(page.locator('.kpi-card').nth(4)).toContainText('4');
  await page.getByLabel('Camera preset').selectOption('MP1');await expect(page.locator('.slot-grid button')).toHaveCount(16);
  await page.reload();await expect(claim.getByTestId('claim-remaining')).toHaveText('15 kg');
  await expect(page.locator('.kpi-card').nth(4)).toContainText('4');
  await page.getByRole('button',{name:'RESET SIMULATION'}).click();
  await expect(claim.getByTestId('claim-remaining')).toHaveText('25 kg');
  const storage=await page.evaluate(()=>JSON.parse(localStorage.getItem('pepeg-digital-twin-sim-v2')));
  expect(storage.state.stacks).toHaveLength(112);expect(storage.state.stacks.find(s=>s.id==='18/A02').reserved).not.toBe(400);
  expect(external).toEqual([]);expect(errors).toEqual([]);
});
